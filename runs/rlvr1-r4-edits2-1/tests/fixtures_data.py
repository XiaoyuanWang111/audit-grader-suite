"""Labeled fixtures: short responses labeled from audit/CONTRACTS.md alone (proposed readings).

Each fixture: check id, kwargs, response (the graded text), label (True = pass), kind
("control", "finding" or "decision"), ref (finding id or decision entry; filled from the run, see
ISSUE.md), and `wrong` = the graders whose current verdict differs from the label
("nvidia" = NVIDIA checker as the SkyRL reward runs it, "verifyit" = verifyit check as the task-curation
gate runs it, "replacement" = audit/lib/contracts_grader.py with the proposed readings). A grader in
`wrong` is marked xfail(strict=True) in test_fixtures.py, so a fix must remove the mark.
`na` lists graders that do not grade the check (verifyit sends the four semantic ids to the judge).
"""
